const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// слово должно начинаться с этого фрагмента: «рис», но не «редис»
const MATCHERS = RULES.map(
  ([category, stems]) => [category, new RegExp(`(?<![а-яa-z])(?:${stems.map(escape).join('|')})`)] as const,
);

/** Отдел магазина по названию продукта. */
export function categorize(name: string): Category {
  const s = name.toLowerCase().replace(/ё/g, 'е');
  return MATCHERS.find(([, re]) => re.test(s))?.[0] ?? 'Другое';
}
